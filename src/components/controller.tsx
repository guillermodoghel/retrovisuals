"use client";

import { useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState } from "react";
import { STAGE_ID, type VisualsMessage } from "@/components/visuals-window";
import PresetGallery from "@/components/preset-gallery";
import { createProjectM, PCM_SAMPLES, type ProjectM } from "@/lib/projectm";

// Same rules as the native version: if it drops below 30fps or the screen goes black, switch presets.
const MIN_FPS = 30;
const BLACK_SECONDS = 3;
const SLOW_SECONDS = 3;
const GRACE_MS = 5000; // time a freshly loaded preset gets before being judged
const MAX_PIXEL_RATIO = 2;
const POPUP_NAME = "retrovisuals";

type AudioSource = { kind: "mic"; deviceId: string } | { kind: "display"; label: string };

// Raw signal, without the browser's voice processing (like the PortAudio input).
const RAW_AUDIO: MediaTrackConstraints = { echoCancellation: false, noiseSuppression: false, autoGainControl: false };

// Index of the .milk files from dependencies/presets-cream-of-the-crop (built by scripts/prepare-assets.mjs).
// Returns name -> file id; the .milk is only downloaded once it's picked.
async function loadPresetIndex(): Promise<Map<string, string>> {
  const res = await fetch("/presets/index.json");
  if (!res.ok) throw new Error("Preset index not found. Run npm run dev / build again.");
  const index: { n: string; f: string }[] = await res.json();
  return new Map(index.map(({ n, f }) => [n, f]));
}

// Generated by scripts/generate-thumbnails.mjs: ids with a thumbnail and ids that crash projectM.
// Without those files the app still works (no images, and broken ones get skipped when played).
async function loadIdList(url: string): Promise<Set<string>> {
  try {
    const res = await fetch(url);
    return new Set(res.ok ? ((await res.json()) as string[]) : []);
  } catch {
    return new Set();
  }
}

function dbToGain(db: number) {
  return Math.pow(10, db / 20);
}

function errorMessage(e: unknown) {
  if (e instanceof DOMException && e.name === "NotAllowedError") {
    return "The browser did not grant permission to capture audio.";
  }
  return e instanceof Error ? e.message : String(e);
}

export default function Controller() {
  const popupRef = useRef<Window | null>(null);
  const popupReadyRef = useRef(false);
  const engineRef = useRef<ProjectM | null>(null);
  const stopRenderRef = useRef<(() => void) | null>(null);
  const attachIdRef = useRef(0);
  const audioCtxRef = useRef<AudioContext | null>(null);
  const gainNodeRef = useRef<GainNode | null>(null);
  const analyserRef = useRef<AnalyserNode | null>(null);
  const sourceRef = useRef<MediaStreamAudioSourceNode | null>(null);
  const streamRef = useRef<MediaStream | null>(null);
  const presetsRef = useRef(new Map<string, string>());
  const milkCacheRef = useRef(new Map<string, string>());
  const selectIdRef = useRef(0);
  const playNextRef = useRef<() => void>(() => {});
  const restartEngineRef = useRef<() => void>(() => {});
  const lastSwitchRef = useRef(0);
  const meterRef = useRef<HTMLDivElement>(null);

  const [status, setStatus] = useState<"idle" | "loading" | "running" | "error">("idle");
  const [error, setError] = useState("");
  const [windowOpen, setWindowOpen] = useState(false);
  const [presetNames, setPresetNames] = useState<string[]>([]);
  const [currentPreset, setCurrentPreset] = useState("");
  const [presetFiles, setPresetFiles] = useState(new Map<string, string>());
  const [thumbs, setThumbs] = useState(new Set<string>());
  const [devices, setDevices] = useState<MediaDeviceInfo[]>([]);
  const [source, setSource] = useState<AudioSource | null>(null);
  const [autoTransitions, setAutoTransitions] = useState(false);
  const [transitionSeconds, setTransitionSeconds] = useState(30);
  const [shuffle, setShuffle] = useState(false);
  const [gainDb, setGainDb] = useState(0);
  const [fps, setFps] = useState(0);

  // The render loop reads settings through refs so it doesn't restart on every change.
  const settingsRef = useRef({ autoTransitions, transitionSeconds, shuffle, currentPreset, presetNames });
  useLayoutEffect(() => {
    settingsRef.current = { autoTransitions, transitionSeconds, shuffle, currentPreset, presetNames };
  });

  const selectPreset = useCallback(async (name: string) => {
    const file = presetsRef.current.get(name);
    if (!file) return;
    const selectId = ++selectIdRef.current;
    // Mark it as current right away so "next" advances correctly even if the download is slow.
    settingsRef.current.currentPreset = name;
    setCurrentPreset(name);
    try {
      let milk = milkCacheRef.current.get(name);
      if (milk === undefined) {
        const res = await fetch(`/presets/${file}.milk`);
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        // .milk files come from Windows: latin1, not UTF-8.
        milk = new TextDecoder("latin1").decode(await res.arrayBuffer());
        milkCacheRef.current.set(name, milk);
        if (selectId !== selectIdRef.current) return; // another one was picked while downloading
      }
      engineRef.current?.loadPreset(milk);
      lastSwitchRef.current = performance.now();
    } catch (e) {
      if (selectId === selectIdRef.current) skipBrokenPreset(name, e);
    }
  }, []);

  // Removes a broken preset from the list and moves on to the one after it. If projectM aborted
  // (some .milk files crash it), the WASM module is unusable: boot a fresh one.
  function skipBrokenPreset(name: string, e: unknown) {
    const aborted = String(e).includes("RuntimeError"); // Aborted, memory access out of bounds, etc.
    console.warn(`Broken preset, skipping: ${name}`, e);
    presetsRef.current.delete(name);
    const names = settingsRef.current.presetNames;
    const index = names.indexOf(name);
    if (index !== -1) {
      // "next" has to continue from the same position in the list.
      // Also in state: the ref gets re-synced from there on every render.
      const previous = names[(index - 1 + names.length) % names.length];
      settingsRef.current.currentPreset = previous;
      settingsRef.current.presetNames = names.filter((n) => n !== name);
      setCurrentPreset(previous);
      setPresetNames(settingsRef.current.presetNames);
    }
    if (aborted) {
      engineRef.current = null;
      restartEngineRef.current();
    } else {
      playNextRef.current();
    }
  }

  const playNextPreset = useCallback(() => {
    const { presetNames: names, currentPreset: current, shuffle: shuffled } = settingsRef.current;
    if (names.length === 0) return;
    let next: string;
    if (shuffled && names.length > 1) {
      do next = names[Math.floor(Math.random() * names.length)];
      while (next === current);
    } else {
      next = names[(names.indexOf(current) + 1) % names.length];
    }
    selectPreset(next);
  }, [selectPreset]);
  useLayoutEffect(() => {
    playNextRef.current = playNextPreset;
  });

  const ensureAudioGraph = useCallback(() => {
    if (audioCtxRef.current) return;
    const ctx = new AudioContext();
    // Mono -> stereo: the same sample on both channels, just like the PortAudio callback did.
    const gain = ctx.createGain();
    gain.channelCount = 2;
    gain.channelCountMode = "explicit";
    gain.channelInterpretation = "speakers";
    gain.gain.value = dbToGain(gainDb);
    const analyser = ctx.createAnalyser();
    analyser.fftSize = PCM_SAMPLES;
    gain.connect(analyser);
    audioCtxRef.current = ctx;
    gainNodeRef.current = gain;
    analyserRef.current = analyser;
  }, [gainDb]);

  const connectStream = useCallback((stream: MediaStream, next: AudioSource) => {
    const ctx = audioCtxRef.current!;
    sourceRef.current?.disconnect();
    streamRef.current?.getTracks().forEach((t) => t.stop());

    const node = ctx.createMediaStreamSource(new MediaStream(stream.getAudioTracks()));
    node.connect(gainNodeRef.current!);
    sourceRef.current = node;
    streamRef.current = stream;
    setSource(next);
  }, []);

  const connectMicrophone = useCallback(
    async (deviceId?: string) => {
      const stream = await navigator.mediaDevices.getUserMedia({
        audio: { ...RAW_AUDIO, deviceId: deviceId ? { exact: deviceId } : undefined },
      });
      connectStream(stream, { kind: "mic", deviceId: stream.getAudioTracks()[0]?.getSettings().deviceId ?? "" });
      const inputs = (await navigator.mediaDevices.enumerateDevices()).filter((d) => d.kind === "audioinput");
      setDevices(inputs);
    },
    [connectStream],
  );

  // getDisplayMedia needs a user gesture: it has to be called straight from the click, with no awaits before it.
  const connectComputerAudio = useCallback(() => {
    setError("");
    ensureAudioGraph();
    navigator.mediaDevices
      .getDisplayMedia({
        video: true,
        audio: { ...RAW_AUDIO, suppressLocalAudioPlayback: false } as MediaTrackConstraints,
        // Chrome options that aren't in lib.dom yet.
        ...{ systemAudio: "include", selfBrowserSurface: "exclude" },
      })
      .then((stream) => {
        const [track] = stream.getAudioTracks();
        if (!track) {
          stream.getTracks().forEach((t) => t.stop());
          throw new Error(
            'What you shared has no audio. Pick a tab or the entire screen and turn on "Share audio".',
          );
        }
        // If sharing is stopped from Chrome's bar, fall back to the microphone.
        track.addEventListener("ended", () => {
          if (streamRef.current === stream) {
            setError("Audio sharing stopped. Switched back to the microphone.");
            connectMicrophone().catch((e) => setError(errorMessage(e)));
          }
        });
        connectStream(stream, { kind: "display", label: track.label || "Computer audio" });
      })
      .catch((e) => setError(errorMessage(e)));
  }, [ensureAudioGraph, connectMicrophone, connectStream]);

  const detachVisuals = useCallback(() => {
    stopRenderRef.current?.();
    stopRenderRef.current = null;
    popupReadyRef.current = false;
    setFps(0);
  }, []);

  // Draws on the visuals window's canvas (same origin, so the panel drives it directly).
  const attachVisuals = useCallback(async () => {
    const popup = popupRef.current;
    const ctx = audioCtxRef.current;
    const analyser = analyserRef.current;
    if (!popup || popup.closed || !popupReadyRef.current || !ctx || !analyser) return;
    const presetNames = settingsRef.current.presetNames;
    if (presetNames.length === 0) return;
    const stage = popup.document.getElementById(STAGE_ID);
    if (!stage) return;

    // Work in whole physical pixels: the canvas doesn't inherit the screen density on its own.
    const targetSize = () => {
      const pixelRatio = Math.min(popup.devicePixelRatio || 1, MAX_PIXEL_RATIO);
      return {
        width: Math.max(1, Math.round(popup.innerWidth * pixelRatio)),
        height: Math.max(1, Math.round(popup.innerHeight * pixelRatio)),
      };
    };
    const initial = targetSize();

    const attachId = ++attachIdRef.current;
    stopRenderRef.current?.();
    stopRenderRef.current = null;
    // New canvas on every start: the WebGL context of an aborted module can't be reused.
    const canvas = popup.document.createElement("canvas");
    canvas.id = `retro-canvas-${attachId}`;
    canvas.style.cssText = "position:absolute;inset:0;width:100%;height:100%;display:block";
    canvas.width = initial.width;
    canvas.height = initial.height;
    stage.replaceChildren(canvas);
    let engine: ProjectM;
    try {
      engine = await createProjectM(popup, canvas);
    } catch (e) {
      setError(errorMessage(e));
      return;
    }
    if (attachId !== attachIdRef.current || popup.closed) {
      engine.destroy(); // another attach is already in progress
      return;
    }
    engineRef.current = engine;
    // Start with the one after the current preset (or a random one the first time).
    if (settingsRef.current.currentPreset) playNextPreset();
    else selectPreset(presetNames[Math.floor(Math.random() * presetNames.length)]);

    // The size is checked every frame (covers resizing, fullscreen and moving to a monitor with a different
    // density) and only applied once it stops changing: every resize reallocates projectM's
    // framebuffers, so while the edge is being dragged the canvas is just stretched via CSS.
    const RESIZE_SETTLE_MS = 150;
    let pendingSize = "";
    let pendingSince = 0;
    let lastResize = 0;
    const syncSize = (now: number) => {
      const { width, height } = targetSize();
      if (width === canvas.width && height === canvas.height) {
        pendingSize = "";
        return;
      }
      const key = `${width}x${height}`;
      if (key !== pendingSize) {
        pendingSize = key;
        pendingSince = now;
        return;
      }
      if (now - pendingSince < RESIZE_SETTLE_MS) return;
      canvas.width = width;
      canvas.height = height;
      engine.resize(width, height);
      pendingSize = "";
      lastResize = now;
    };

    const probe = document.createElement("canvas");
    probe.width = probe.height = 16;
    const probeCtx = probe.getContext("2d", { willReadFrequently: true })!;
    const isFrameBlack = () => {
      // Read in the same tick as the render, before the browser discards the WebGL buffer.
      probeCtx.drawImage(canvas, 0, 0, probe.width, probe.height);
      const { data } = probeCtx.getImageData(0, 0, probe.width, probe.height);
      for (let i = 0; i < data.length; i += 4) {
        if (data[i] > 8 || data[i + 1] > 8 || data[i + 2] > 8) return false;
      }
      return true;
    };

    const pcm = new Float32Array(PCM_SAMPLES);
    let raf = 0;
    let frames = 0;
    let windowStart = performance.now();
    let blackSeconds = 0;
    let slowSeconds = 0;

    // Use the visuals window's requestAnimationFrame: it keeps running at full speed even if the panel is in the background.
    const tick = () => {
      raf = popup.requestAnimationFrame(tick);
      const now = performance.now();
      syncSize(now);
      try {
        analyser.getFloatTimeDomainData(pcm);
        engine.addPcm(pcm);
        engine.render();
      } catch (e) {
        popup.cancelAnimationFrame(raf);
        skipBrokenPreset(settingsRef.current.currentPreset, e);
        return;
      }
      frames++;

      const elapsed = now - windowStart;
      if (elapsed < 1000) return;

      const currentFps = (frames * 1000) / elapsed;
      setFps(Math.round(currentFps));
      frames = 0;
      windowStart = now;

      const { autoTransitions: auto, transitionSeconds: seconds } = settingsRef.current;
      const sinceSwitch = now - lastSwitchRef.current;

      if (auto && sinceSwitch >= seconds * 1000) {
        playNextPreset();
        return;
      }
      // After a preset or size change, allow some slack before judging fps / black screen.
      if (sinceSwitch < GRACE_MS || now - lastResize < GRACE_MS || popup.document.hidden) {
        blackSeconds = slowSeconds = 0;
        return;
      }

      blackSeconds = isFrameBlack() ? blackSeconds + 1 : 0;
      slowSeconds = currentFps < MIN_FPS ? slowSeconds + 1 : 0;
      if (blackSeconds >= BLACK_SECONDS || slowSeconds >= SLOW_SECONDS) {
        blackSeconds = slowSeconds = 0;
        playNextPreset();
      }
    };
    raf = popup.requestAnimationFrame(tick);

    stopRenderRef.current = () => {
      if (engineRef.current === engine) engineRef.current = null;
      if (!popup.closed) {
        popup.cancelAnimationFrame(raf);
        try {
          engine.destroy();
        } catch {
          // an aborted module may throw when destroyed; discard it anyway
        }
      }
    };
    popup.postMessage({ type: "attached" } satisfies VisualsMessage, window.location.origin);
  }, [playNextPreset, selectPreset]);

  useLayoutEffect(() => {
    restartEngineRef.current = attachVisuals;
  });

  const openVisualsWindow = useCallback(() => {
    const popup = window.open("/visuals", POPUP_NAME, "popup,width=1280,height=720");
    if (!popup) {
      setError("The browser blocked the visuals window. Allow pop-ups for this site and try again.");
      return false;
    }
    if (popupRef.current !== popup) detachVisuals();
    popupRef.current = popup;
    setWindowOpen(true);
    popup.focus();
    return true;
  }, [detachVisuals]);

  const start = useCallback(async () => {
    setError("");
    setStatus("loading");
    // Open the window first, inside the click, so the browser doesn't block it.
    openVisualsWindow();
    try {
      ensureAudioGraph();
      await audioCtxRef.current!.resume();
      const [presets, thumbIds, brokenIds, emptyIds] = await Promise.all([
        loadPresetIndex(),
        loadIdList("/thumbs/index.json"),
        loadIdList("/thumbs/broken.json"),
        loadIdList("/thumbs/empty.json"), // the ones that show nothing (scripts/find-empty-presets.mjs)
        connectMicrophone(),
      ]);
      for (const [name, file] of presets) if (brokenIds.has(file) || emptyIds.has(file)) presets.delete(name);
      presetsRef.current = presets;
      setPresetFiles(new Map(presets));
      setThumbs(thumbIds);
      const names = [...presets.keys()].sort((a, b) => a.localeCompare(b));
      settingsRef.current.presetNames = names;
      setPresetNames(names);
      setStatus("running");
      // If the window already reported it loaded, attach now; otherwise, when its "ready" arrives.
      attachVisuals();
    } catch (e) {
      setStatus("error");
      setError(errorMessage(e));
    }
  }, [ensureAudioGraph, openVisualsWindow, connectMicrophone, attachVisuals]);

  useEffect(() => {
    const onMessage = (e: MessageEvent<VisualsMessage>) => {
      if (e.origin !== window.location.origin || e.source !== popupRef.current) return;
      if (e.data?.type === "ready") {
        popupReadyRef.current = true;
        attachVisuals();
      } else if (e.data?.type === "next") {
        playNextPreset();
      }
    };
    window.addEventListener("message", onMessage);
    return () => window.removeEventListener("message", onMessage);
  }, [attachVisuals, playNextPreset]);

  // Detect when the visuals window is closed.
  useEffect(() => {
    if (!windowOpen) return;
    const id = setInterval(() => {
      if (popupRef.current?.closed) {
        detachVisuals();
        popupRef.current = null;
        setWindowOpen(false);
      }
    }, 500);
    return () => clearInterval(id);
  }, [windowOpen, detachVisuals]);

  // Input level meter, to see that audio is coming in.
  useEffect(() => {
    if (status !== "running") return;
    const data = new Float32Array(1024);
    let raf = 0;
    const tick = () => {
      raf = requestAnimationFrame(tick);
      const analyser = analyserRef.current;
      if (!analyser || !meterRef.current) return;
      analyser.getFloatTimeDomainData(data);
      let peak = 0;
      for (const v of data) peak = Math.max(peak, Math.abs(v));
      meterRef.current.style.width = `${Math.min(100, peak * 100)}%`;
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [status]);

  useEffect(() => {
    if (status !== "running") return;
    const onKey = (e: KeyboardEvent) => {
      const typing = e.target instanceof HTMLInputElement || e.target instanceof HTMLSelectElement;
      if (e.key === " " && !typing) {
        e.preventDefault();
        playNextPreset();
      }
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [status, playNextPreset]);

  useEffect(() => {
    if (gainNodeRef.current) gainNodeRef.current.gain.value = dbToGain(gainDb);
  }, [gainDb]);

  useEffect(() => {
    const closePopup = () => popupRef.current?.close();
    window.addEventListener("pagehide", closePopup);
    return () => {
      window.removeEventListener("pagehide", closePopup);
      streamRef.current?.getTracks().forEach((t) => t.stop());
      audioCtxRef.current?.close();
    };
  }, []);

  // Only the ones still in the list (broken ones get removed along the way).
  const galleryPresets = useMemo(
    () => new Map(presetNames.map((n) => [n, presetFiles.get(n) ?? ""])),
    [presetNames, presetFiles],
  );

  if (status !== "running") {
    return (
      <main className="flex h-full flex-col items-center justify-center gap-6 p-8 text-center">
        <h1 className="text-4xl font-bold tracking-tight">RetroVisuals</h1>
        <p className="max-w-md text-sm text-zinc-400">
          Milkdrop visuals in your browser. This tab is the control panel; the visuals open in a separate window
          that you can move to another monitor.
        </p>
        <button
          onClick={start}
          disabled={status === "loading"}
          className="rounded-full border border-zinc-600 px-8 py-3 text-sm uppercase tracking-widest transition hover:bg-zinc-100 hover:text-black disabled:opacity-50"
        >
          {status === "loading" ? "Loading…" : "Start"}
        </button>
        {error && <p className="max-w-md text-sm text-red-400">{error}</p>}
      </main>
    );
  }

  return (
    <main className="mx-auto grid h-full max-w-[1600px] gap-4 overflow-y-auto p-4 text-xs md:grid-cols-[minmax(0,1fr)_380px] md:overflow-hidden">
      <PresetGallery presets={galleryPresets} thumbs={thumbs} current={currentPreset} onSelect={selectPreset} />

      <div className="flex min-h-0 flex-col gap-4 overflow-y-auto">
        <section className="flex flex-col gap-3 rounded-lg border border-zinc-800 p-4">
          <header className="flex items-center justify-between">
            <h1 className="text-sm font-bold">RetroVisuals</h1>
            <span className="text-zinc-500">{windowOpen ? `${fps} fps` : "window closed"}</span>
          </header>
          <p className="truncate">
            <span className="text-zinc-500">Current preset: </span>
            {currentPreset}
          </p>
          <div className="flex gap-2">
            {windowOpen ? (
              <>
                <button
                  onClick={() => popupRef.current?.focus()}
                  className="flex-1 rounded border border-zinc-700 px-3 py-2 hover:bg-zinc-800"
                >
                  Go to visuals
                </button>
                <button
                  onClick={() => popupRef.current?.close()}
                  className="rounded border border-zinc-700 px-3 py-2 hover:bg-zinc-800"
                >
                  Close
                </button>
              </>
            ) : (
              <button
                onClick={openVisualsWindow}
                className="flex-1 rounded bg-zinc-100 px-3 py-2 font-bold text-black hover:bg-white"
              >
                Open visuals
              </button>
            )}
            <button onClick={playNextPreset} className="rounded border border-zinc-700 px-3 py-2 hover:bg-zinc-800">
              Next ⏭
            </button>
          </div>
          <p className="text-zinc-500">
            Drag the window to the other monitor and double-click inside it for fullscreen. Space: next
            preset.
          </p>
        </section>

        <section className="flex flex-col gap-3 rounded-lg border border-zinc-800 p-4">
          <h2 className="text-sm font-bold">Audio</h2>
          <label className="flex flex-col gap-1">
            <span className="text-zinc-500">Microphone / input</span>
            <select
              value={source?.kind === "mic" ? source.deviceId : ""}
              onChange={(e) => {
                setError("");
                connectMicrophone(e.target.value).catch((err) => setError(errorMessage(err)));
              }}
              className="rounded border border-zinc-700 bg-zinc-900 px-2 py-1.5"
            >
              {source?.kind !== "mic" && <option value="">—</option>}
              {devices.map((d, i) => (
                <option key={d.deviceId} value={d.deviceId}>
                  {d.label || `Microphone ${i + 1}`}
                </option>
              ))}
            </select>
          </label>
          <button
            onClick={connectComputerAudio}
            className={`rounded border px-3 py-2 text-left ${
              source?.kind === "display" ? "border-zinc-300 bg-zinc-800" : "border-zinc-700 hover:bg-zinc-800"
            }`}
          >
            🔊 {source?.kind === "display" ? `Listening: ${source.label}` : "Use computer audio"}
          </button>
          <p className="text-zinc-500">
            Chrome asks what to share: pick a tab (Spotify, YouTube…) or the entire screen, and turn on
            &quot;Share audio&quot;. If your Mac doesn&apos;t offer that option for the entire screen, install{" "}
            <a href="https://existential.audio/blackhole/" target="_blank" rel="noreferrer" className="underline">
              BlackHole
            </a>{" "}
            and pick it above as the microphone.
          </p>
          <div className="h-1.5 overflow-hidden rounded bg-zinc-800">
            <div ref={meterRef} className="h-full w-0 bg-zinc-200" />
          </div>
          <label className="flex flex-col gap-1">
            <span className="text-zinc-500">Gain: {gainDb.toFixed(1)} dB</span>
            <input
              type="range"
              min={-30}
              max={30}
              step={0.5}
              value={gainDb}
              onChange={(e) => setGainDb(Number(e.target.value))}
            />
          </label>
        </section>

        <section className="flex flex-wrap items-center gap-x-6 gap-y-2 rounded-lg border border-zinc-800 p-4">
          <label className="flex items-center gap-2">
            <input type="checkbox" checked={autoTransitions} onChange={(e) => setAutoTransitions(e.target.checked)} />
            Auto transitions
          </label>
          {autoTransitions && (
            <label className="flex items-center gap-2">
              Seconds
              <input
                type="number"
                min={1}
                value={transitionSeconds}
                onChange={(e) => setTransitionSeconds(Math.max(1, Number(e.target.value) || 1))}
                className="w-20 rounded border border-zinc-700 bg-zinc-900 px-2 py-1"
              />
            </label>
          )}
          <label className="flex items-center gap-2">
            <input type="checkbox" checked={shuffle} onChange={(e) => setShuffle(e.target.checked)} />
            Shuffle
          </label>
        </section>

        {error && <p className="text-red-400">{error}</p>}

        <p className="text-zinc-500">
          Coded with manija by el wisho ·{" "}
          <a
            href="https://github.com/guillermodoghel/retrovisuals"
            target="_blank"
            rel="noreferrer"
            className="underline"
          >
            source
          </a>
        </p>
      </div>
    </main>
  );
}
